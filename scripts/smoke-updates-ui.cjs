const { app, BrowserWindow, ipcMain } = require("electron");
const fs = require("node:fs"), os = require("node:os"), path = require("node:path"), { pathToFileURL } = require("node:url");
const root = path.resolve(__dirname, ".."), uiRoot = path.resolve(process.argv.find(arg => arg.startsWith("--ui-root="))?.slice(10) || root);
const profile = fs.mkdtempSync(path.join(os.tmpdir(), "cfb-update-ui-"));
app.setPath("userData", profile); app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const { EventEmitter } = require("node:events");
  const { UpdateService } = await import(pathToFileURL(path.join(root, "src/main/services/updates.js")));
  const { registrySnapshot } = await import(pathToFileURL(path.join(root, "src/shared/toolRegistry.js")));
  let window, busy = false, offline = false, phase = "checking", downloaded = 0, installed = 0, prompts = 0;
  const updater = new EventEmitter();
  updater.checkForUpdates = async () => { if (offline) throw new Error("Offline test"); updater.emit("update-available", { version: "0.18.1" }); };
  updater.downloadUpdate = async () => { downloaded++; updater.emit("download-progress", { percent: 37 }); };
  updater.quitAndInstall = () => { installed++; };
  const service = new UpdateService({ updater, currentVersion: "0.18.0", busy: () => busy, prompt: async () => { prompts++; return false; }, emit: status => { phase = status.phase; window?.webContents.send("updates:status-changed", status); } });
  ipcMain.handle("updates:status", () => service.snapshot());
  ipcMain.handle("updates:check", () => service.check());
  ipcMain.handle("updates:download", () => service.download());
  ipcMain.handle("updates:install", () => service.install());
  ipcMain.handle("app:bootstrap", () => ({ app: { name: "Ace's CFB Toolkit", version: "0.18.0", schemas: ["C27_486_6"] }, registry: registrySnapshot(), settings: { theme: "light", toolPresets: [] }, activeSave: null }));
  ipcMain.handle("history:list", () => []);
  window = new BrowserWindow({ show: false, width: 1380, height: 860, webPreferences: { preload: path.join(uiRoot, "src/main/preload.cjs"), sandbox: true, contextIsolation: true, backgroundThrottling: false, offscreen: true } });
  await window.loadFile(path.join(uiRoot, "src/renderer/index.html"));
  const evaluate = source => window.webContents.executeJavaScript(source);
  await evaluate(`(async () => {
    const wait = async predicate => { for (let i=0;i<200;i++) { if(predicate()) return; await new Promise(resolve=>setTimeout(resolve,25)); } throw new Error('UI wait timed out'); };
    await wait(()=>state.bootstrap); navigate('settings');
    await wait(()=>document.querySelector('[data-update-action="checkForUpdates"]'));
    document.querySelector('[data-update-action="checkForUpdates"]').click();
    await wait(()=>document.querySelector('#update-notice [data-update-action="downloadUpdate"]'));
    if(document.querySelector('#update-notice').hidden) throw new Error('Available update notice missing');
    document.querySelector('#update-notice [data-update-action="downloadUpdate"]').click();
    await wait(()=>document.querySelector('#update-notice progress')?.value===37);
    if(!document.querySelector('#update-settings-status progress')) throw new Error('Settings missing progress');
  })()`);
  if (downloaded !== 1 || prompts !== 1 || updater.autoInstallOnAppQuit) throw new Error("Consent/duplicate download failed");
  busy = true; updater.emit("update-downloaded", { version: "0.18.1" });
  await evaluate(`(async () => {
    await new Promise(resolve=>setTimeout(resolve,80));
    document.querySelector('#update-notice [data-update-action="installUpdate"]').click();
    await new Promise(resolve=>setTimeout(resolve,80));
    if(!document.querySelector('#update-notice').textContent.includes('current tool operation')) throw new Error('Busy-run safeguard not shown');
  })()`);
  if (installed || prompts !== 1) throw new Error("Busy operation interrupted");
  busy = false; await service.offer();
  await evaluate(`(async () => {
    await new Promise(resolve=>setTimeout(resolve,80));
    if(!document.querySelector('#update-notice [data-update-action="installUpdate"]')) throw new Error('Later lost ready update');
    navigate('long-snap'); navigate('settings');
    if(!document.querySelector('#update-settings-status [data-update-action="installUpdate"]')) throw new Error('Status lost on navigation');
    document.querySelector('[data-update-dismiss]').click();
    if(!document.querySelector('#update-notice').hidden) throw new Error('Notice dismissal failed');
    if(!document.querySelector('#update-settings-status [data-update-action="installUpdate"]')) throw new Error('Dismissing notice removed Settings controls');
    document.documentElement.dataset.theme='dark';
  })()`);
  if (installed || prompts !== 2) throw new Error("Later unexpectedly installed");
  fs.mkdirSync(path.join(root, "outputs"), { recursive: true });
  fs.writeFileSync(path.join(root, "outputs/update-settings-smoke.png"), (await window.webContents.capturePage()).toPNG());
  service.set({ phase: "idle", message: "Ready" }); offline = true; await service.check();
  await evaluate(`(async () => {
    await new Promise(resolve=>setTimeout(resolve,80));
    if(!document.querySelector('#update-notice').hidden) throw new Error('Offline banner obscures app');
    if(!document.querySelector('#update-settings-status').textContent.includes('still usable')) throw new Error('Offline explanation missing');
    if(!document.querySelector('#update-settings-status [data-update-action="checkForUpdates"]')) throw new Error('Retry missing');
  })()`);
  if (phase !== "error") throw new Error("Expected offline test state");
  console.log("Update UI passed: manual check, available notice, Download/Later consent, live progress, busy-run safeguard, Restart/Later, navigation, dismissible notice, offline retry.");
  window.destroy(); app.quit();
}).catch(error => { console.error(error.stack); app.exit(1); });
